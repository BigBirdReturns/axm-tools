'use strict';
const assert = require('node:assert/strict');
require('../engine.js');
const engine = globalThis.SimEngine;
(async function () {
  assert.equal(engine.version, '1.0.0');
  assert.equal(engine.canonical({ z: 3, a: [2, 1] }), engine.canonical({ a: [2, 1], z: 3 }));
  assert.throws(() => engine.canonical({ invalid: Infinity }), /Non-finite/);
  const nominal = engine.run();
  assert.equal(nominal.passed, true, 'Nominal reactive baseline must meet the fixed disclosed criteria');
  assert.equal(nominal.frames.length, 240);
  assert.deepEqual(engine.run(), nominal, 'Same config must reproduce all unsealed evidence exactly');
  assert.notDeepEqual(engine.run({ seed: 73 }).frames, nominal.frames, 'A fresh noise seed must alter observations');
  const reactive = engine.run({ fault: 'dropout' });
  const supported = engine.run({ controller: 'supported', fault: 'dropout' });
  assert.equal(reactive.passed, false, 'Fault exposure must be able to invalidate a nominally passing controller');
  assert(reactive.checks.some(c => !c.passed && c.id === 'peak-error'));
  assert(supported.metrics.maxError < reactive.metrics.maxError, 'Predictive support must change actual trajectory, not only a pass flag');
  assert.equal(supported.passed, true);
  assert(reactive.frames.some(f => !f.measurementDelivered));
  assert(reactive.frames.some(f => f.staleSeconds > 1));
  assert.equal(engine.run({ controller: 'reactive', fault: 'delay' }).passed, false);
  assert.equal(engine.run({ controller: 'supported', fault: 'delay' }).passed, true);
  const biased = engine.run({ controller: 'supported', fault: 'bias' });
  assert.equal(biased.passed, false, 'Support must not conceal an unobservable sensor bias');
  const prolonged = engine.run({ controller: 'supported', fault: 'dropout', ticks: 400 });
  assert(prolonged.metrics.expiredTicks > 0);
  assert.equal(prolonged.checks.find(c => c.id === 'measurement-age').passed, false);
  assert(prolonged.frames.filter(f => f.staleExpired).every(f => f.vx === 0 && f.vy === 0), 'Expired supported observations must invoke explicit safe stop');
  for (const key of ['maxError', 'rmsError', 'finalError']) assert.equal(nominal.criteria[key], biased.criteria[key], 'Criteria must be identical across candidates and faults');
  assert.equal(engine.limits.maxError, 0.28);
  assert(Object.isFrozen(engine.limits));
  const suite = engine.runSuite();
  assert.equal(suite.total, 12);
  assert.equal(suite.passed, 9);
  assert.equal(suite.allPassed, false, 'Default fresh-seed suite includes negative bias cases and must not auto-admit a candidate');
  assert.equal(suite.runs.filter(r => r.config.fault === 'bias').every(r => !r.passed), true);
  assert.match(suite.cohort, /fresh-seed/);
  assert.match(engine.runSuite({ seeds: [42], faults: ['none'] }).cohort, /development/);
  assert.equal(engine.developmentSeeds.some(s => engine.freshSeeds.includes(s)), false);
  assert.throws(() => engine.run({ controller: 'magic' }), /Unknown/);
  assert.throws(() => engine.run({ fault: 'magic' }), /Unknown/);
  assert.throws(() => engine.run({ ticks: 0 }), /ticks/);
  assert.throws(() => engine.run({ dt: NaN }), /ticks/);
  assert.throws(() => engine.runSuite({ seeds: [] }), /Suite/);
  assert.equal(await engine.verify(nominal), false, 'Unsealed evidence is not verified');
  await engine.seal(nominal);
  assert.equal(nominal.integrity.digest.length, 64);
  assert.equal(await engine.integrity.verify(nominal), true);
  const clone = JSON.parse(JSON.stringify(nominal));
  clone.frames[50].x += 0.01;
  assert.equal(await engine.verify(clone), false, 'A single trajectory edit must break the seal');
  const configTamper = JSON.parse(JSON.stringify(nominal));
  configTamper.config.seed = 1;
  assert.equal(await engine.verify(configTamper), false);
  const decisionTamper = JSON.parse(JSON.stringify(nominal));
  decisionTamper.passed = false;
  assert.equal(await engine.verify(decisionTamper), false, 'Decision-bearing fields must also be sealed');
  const criteriaTamper = JSON.parse(JSON.stringify(nominal));
  criteriaTamper.criteria.maxError = 999;
  assert.equal(await engine.verify(criteriaTamper), false);
  const same = await engine.seal(engine.run());
  assert.equal(same.integrity.digest, nominal.integrity.digest, 'Identical complete evidence must have identical digests');
  console.log('PASS: deterministic simulation, actual perturbations, fixed criteria, negative gates, fresh-seed regression and SHA-256 tamper checks.');
  console.log('Fresh suite: ' + suite.passed + '/' + suite.total + '; allPassed=' + suite.allPassed + '. Bias remains a release blocker.');
})().catch(error => { console.error(error); process.exitCode = 1; });
