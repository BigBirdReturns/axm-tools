'use strict';
const assert = require('node:assert/strict');
const C = require('../capture.js');
require('../recorded.js');
const original = globalThis.DR_RECORDED.assets['frames.SYNTHETIC_EXAMPLE.csv'];
const report = C.inspectFrames(original);
assert.equal(report.receivedFrames, 6);
assert.equal(report.explicitMissing, 1);
assert.equal(report.sequenceGaps, 0, 'Explicit absent row is not double-counted as an unrepresented gap');
assert.equal(report.lateArrivals, 1, 'Pi arrival order must expose frame 104 even when CSV is sequence sorted');
assert.equal(report.lateArrivalDetails[0].frameSeq, '104');
assert.equal(report.queueLatencyMs.count, 6);
assert.equal(report.queueLatencyMs.min, 6);
assert.equal(report.queueLatencyMs.median, 7);
assert.equal(report.queueLatencyMs.max, 7);
assert.equal(report.valid, true);
const changedClocks = original.replace(/CAMERA_PTS/g, 'UNRELATED_CLOCK').replace(/1000000000/g, '99999999999999999999999999');
assert.deepEqual(C.inspectFrames(changedClocks).queueLatencyMs, report.queueLatencyMs, 'Unrelated camera clock cannot change Pi queue calculations');
const headers = 'frame_seq,camera_timestamp_ns,camera_clock_id,pi_received_monotonic_ns,consumer_seen_monotonic_ns,status,image_ref\n';
const precise = headers + '9007199254740993,1,OTHER,9007199254740993000,9007199254740993001,delivered,"asset,one"\n';
const precision = C.inspectFrames(precise);
assert.equal(precision.queueSamples[0].latencyNs, '1');
assert.equal(precision.queueLatencyMs.min, 0.000001, 'Nanosecond difference must be computed before converting to Number');
assert.equal(C.parseCSV(precise)[0].image_ref, 'asset,one');
const quoted = C.parseCSV('a,b\r\n"hello,\nworld","said ""yes"""\r\n');
assert.equal(quoted[0].a, 'hello,\nworld');
assert.equal(quoted[0].b, 'said "yes"');
assert.throws(() => C.parseCSV('a,b\n"unclosed,x'), /Unclosed/);
assert.throws(() => C.parseCSV('a,b\n"x"extra,y'), /Unexpected/);
assert.throws(() => C.parseCSV('a,b\nx"y,z'), /Quote/);
assert.throws(() => C.parseCSV('a,b\nx,y,z'), /fields/);
assert.throws(() => C.parseCSV('a,a\nx,y'), /unique/);
assert.throws(() => C.inspectFrames('a,b\nx,y'), /headers/);
assert.throws(() => C.parseCSV('x'.repeat(C.limits.maxBytes + 1)), /5 MiB/);
assert.throws(() => C.parseCSV('a\n' + 'x\n'.repeat(20001)), /20000/);
const negative = C.inspectFrames(headers + '1,1,C,100,99,delivered,a\n');
assert.equal(negative.valid, false);
assert.equal(negative.queueLatencyMs.count, 0);
assert(negative.invalidRows[0].reasons.some(s => s.includes('Negative')));
const pureGap = C.inspectFrames(headers + '100,1,C,100,200,delivered,a\n104,2,C,200,300,delivered,b\n');
assert.equal(pureGap.sequenceGaps, 3);
assert.deepEqual(pureGap.sequenceGapRanges[0], { sessionId: '(unspecified session)', from: '101', to: '103', count: '3' });
const duplicate = C.inspectFrames(headers + '1,1,C,100,200,delivered,a\n1,2,C,200,300,delivered,b\n');
assert.equal(duplicate.duplicateSequenceIds[0].frameSeq, '1');
assert.equal(duplicate.duplicateSequenceIds[0].rows.length, 2);
assert.equal(C.inspectFrames(globalThis.DR_RECORDED.assets['frames.template.csv']).receivedFrames, 0);
assert.doesNotThrow(() => JSON.stringify(report), 'Exports cannot contain BigInt values');
const hugeGap = C.inspectFrames(headers + '1,1,C,100,200,delivered,a\n900719925474099300,2,C,200,300,delivered,b\n');
assert.equal(hugeGap.sequenceGapsExact, '900719925474099298');
assert.equal(typeof hugeGap.sequenceGaps, 'string');
const tied = C.inspectFrames(headers + '2,1,C,100,200,delivered,a\n1,2,C,100,300,delivered,b\n');
assert.equal(tied.lateArrivals, 0, 'Identical timestamps do not establish ordering');
console.log('PASS: original template 6 received / 1 explicit missing / 1 late; exact nanosecond differences, clock separation, CSV quoting and limits, gaps, duplicates and negative latency flags.');
