'use strict';
const assert = require('node:assert/strict');
const M = require('../business.js');
const opp = (id, patch = {}) => ({ id, sourceId: 'legacy-' + id, canonicalKey: id, name: 'Fictional ' + id, region: 'EMEA', segment: 'Enterprise', amount: 100, stage: 'Commercial review', owner: 'p1', backup: 'p2', budget: true, buyer: true, procurement: true, customerAcceptance: true, closeDate: '2026-12-15', technical: 'browser', externalEvidence: 'pending', product: 'Illustrative reference', partner: null, duplicateOf: null, ...patch });
const state = () => ({ asOf: '2026-10-27', opportunities: [opp('a')], people: [{ id: 'p1', name: 'Fictional One', role: 'Owner', capacity: 1 }, { id: 'p2', name: 'Fictional Two', role: 'Backup', capacity: 2 }], partners: [], integration: { reconciled: false }, quality: { requiredScope: 'timing', accepted: { scope: 'timing', allPassed: true, verified: true, runIds: ['reference-run'], at: '2026-10-27' }, runs: [], suites: [], curriculum: [] }, actions: [], events: [] });
assert.equal(globalThis.SDModel, M);
assert.equal(M.normalizeStage('Demo'), 'Technical validation');
assert.equal(M.normalizeStage('Negotiation'), 'Commercial review');
let s = state();
assert.equal(M.forecastOne(s.opportunities[0], s).category, 'commit');
s.quality.requiredScope = 'expanded';
assert.equal(M.technicalStatus(s.opportunities[0], s).passed, false, 'Expanded requirements revoke narrower accepted evidence');
assert.notEqual(M.forecastOne(s.opportunities[0], s).category, 'commit');
s.quality.accepted.scope = 'expanded';
assert.equal(M.technicalStatus(s.opportunities[0], s).passed, true);
s.quality.accepted.runIds = [];
assert.equal(M.technicalStatus(s.opportunities[0], s).passed, false);
s = state();
s.opportunities[0].budget = false;
assert.equal(M.technicalStatus(s.opportunities[0], s).passed, true);
assert.equal(M.forecastOne(s.opportunities[0], s).category, 'pipeline', 'Passing technical evidence cannot establish budget');
assert(M.forecastOne(s.opportunities[0], s).blockers.includes('Budget unconfirmed'));
s.opportunities[0].budget = true;
s.opportunities[0].procurement = false;
assert.equal(M.forecastOne(s.opportunities[0], s).category, 'best-case');
s.opportunities[0].procurement = true;
for (const closeDate of ['2026-10-01', '2026-10-27', 'invalid', '2027-02-31']) {
  s.opportunities[0].closeDate = closeDate;
  assert.equal(M.forecastOne(s.opportunities[0], s).category, 'pipeline', 'Invalid/stale close dates must not enter commit or best case');
}
s = state();
s.opportunities.push(opp('copy', { canonicalKey: 'a', stage: 'Negotiation', sourceId: 'other-source' }), opp('b', { stage: 'Demo', amount: 200 }), opp('lost', { stage: 'Closed lost', amount: 999 }), opp('won', { stage: 'Closed won', amount: 300 }));
const reconciliation = M.reconcile(s);
assert.equal(reconciliation.duplicateCount, 1);
assert.equal(reconciliation.normalizedCount, 2);
assert.equal(s.integration.reconciled, true);
assert.equal(s.opportunities.length, 5, 'Source records must be preserved');
assert.equal(s.opportunities[1].sourceId, 'other-source');
assert.equal(s.opportunities[1].duplicateOf, 'a');
assert.equal(M.reconcile(s).changes.length, 0, 'Reconciliation must be idempotent');
assert.equal(M.activeOpportunities(s).length, 3);
const metrics = M.metrics(s);
assert.equal(metrics.openPipeline, 300);
assert.equal(metrics.closedWonBookings, 300);
assert.equal(metrics.recognizedRevenue, null);
assert.equal(metrics.commit, 100);
assert.equal(metrics.bestCase, 200);
assert.equal(metrics.weightedPipeline, 170);
assert.equal(metrics.excludedCount, 2);
assert.equal(M.forecastOne(s.opportunities[1], s).weightedAmount, 0);
let coverage = M.coverage(s);
assert.equal(coverage.people.find(p => p.id === 'p1').overloaded, true);
s.opportunities[2].owner = null;
s.opportunities[2].backup = null;
coverage = M.coverage(s);
assert.equal(coverage.uncovered.length, 1);
assert.equal(coverage.backupGaps.length, 1);
assert.equal(coverage.people.find(p => p.id === 'p1').load, 1);
s.opportunities[2].owner = 'p2';
s.opportunities[2].backup = 'p1';
coverage = M.coverage(s);
assert.equal(coverage.coveragePct, 100);
assert.equal(coverage.backupGaps.length, 0);
const external = opp('external', { technical: 'external', externalEvidence: 'verified' });
assert.equal(M.technicalStatus(external, s).passed, true);
assert.match(M.technicalStatus(external, s).label, /operator-asserted/);
const ranking = M.rankAccounts(s);
assert.equal(ranking.length, 2);
assert.equal(ranking[0].score, Object.values(ranking[0].components).reduce((a, b) => a + b, 0));
const brief = M.commercialBrief(s, 'a');
assert.match(brief.provenance, /Synthetic/);
assert.equal(brief.forecast.category, 'commit');
const review = M.operatingReview(s);
assert.equal(review.metrics.closedWonBookings, 300);
assert.equal(review.metrics.recognizedRevenue, null);
assert.equal(review.coverage.coveragePct, 100);
assert(review.caveats.some(c => c.includes('forecast accuracy')));
assert.equal(M.commercialBrief(s, 'missing').error, 'Opportunity not found');
console.log('PASS: source-preserving dedup, scope-bound acceptance, commercial gates, stale dates, distinct bookkeeping, capacity coverage, transparent ICP and current-state briefs.');
